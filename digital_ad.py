# %% 1 IMPORT LIBRARIES
from pathlib import Path
import csv

import numpy as np
import gymnasium as gym

import matplotlib
matplotlib.use("Agg")  # Save charts without opening a window.
import matplotlib.pyplot as plt


# %% 2 DEFINE THE SIMULATION SETTINGS
OUTPUT = Path(__file__).resolve().parent / "ad_outputs"

PROFILES = [
    "Budget shopper",
    "Tech enthusiast",
    "Fitness enthusiast",
]

PLACEMENTS = [
    "Shopping ad / sidebar",
    "Tech ad / banner",
    "Fitness ad / feed",
]

# Rows represent profiles.
# Columns represent ad/placement choices.
CLICK_PROBABILITIES = np.array([
    [0.12, 0.02, 0.03],  # Budget shopper
    [0.03, 0.16, 0.04],  # Tech enthusiast
    [0.04, 0.03, 0.14],  # Fitness enthusiast
])

# Cost in dollars for displaying each ad once.
COSTS = np.array([0.02, 0.03, 0.025])

# Assumed revenue generated by a click.
CLICK_VALUE = 1.00

TRAIN_EPISODES = 60_000
TEST_IMPRESSIONS = 30_000

LEARNING_RATE = 0.05
DISCOUNT_FACTOR = 0.0
SEED = 42

# %% 3. CREATE THE ADVERTISING ENVIRONMENT
class AdPlacementEnv(gym.Env):
    """Custom Gymnasium simulation with one impression per episode."""

    def __init__(self, seed=42):
        super().__init__()

        self.observation_space = gym.spaces.Discrete(len(PROFILES))
        self.action_space = gym.spaces.Discrete(len(PLACEMENTS))

        super().reset(seed=seed)
        self.state = None

    def reset(self, *, seed=None, options=None):
        super().reset(seed=seed)

        # Introduce a randomly selected visitor profile.
        self.state = int(
            self.np_random.integers(self.observation_space.n)
        )

        return self.state, {}

    def step(self, action):
        if self.state is None:
            raise RuntimeError("Call reset() before displaying an ad.")

        if not self.action_space.contains(action):
            raise ValueError("Action must be 0, 1, or 2.")

        # Simulate a click using this profile/action probability.
        probability = CLICK_PROBABILITIES[self.state, action]
        clicked = int(self.np_random.random() < probability)

        cost = float(COSTS[action])
        revenue = clicked * CLICK_VALUE

        # Positive for valuable clicks; negative for no click.
        reward = revenue - cost

        info = {
            "click": clicked,
            "cost": cost,
            "revenue": revenue,
        }

        # Each impression is a complete episode.
        self.state = None

        next_state = 0  # Placeholder; no future decision follows.
        terminated = True
        truncated = False

        return next_state, reward, terminated, truncated, info

# %% 4. EPSILON-GREEDY ACTION SELECTION
def choose_action(q_table, state, epsilon, rng):
    if rng.random() < epsilon:
        return int(rng.integers(len(PLACEMENTS)))

    # Identify all actions tied for the highest value.
    best_actions = np.flatnonzero(
        q_table[state] == q_table[state].max()
    )

    # Randomly break ties.
    return int(rng.choice(best_actions))
# %%

# %% 5. TRAIN THE Q-LEARNING AGENT
def train_agent():
    env = AdPlacementEnv(seed=SEED)
    action_rng = np.random.default_rng(SEED + 1)

    q_table = np.zeros((
        env.observation_space.n,
        env.action_space.n,
    ))

    history = []

    for episode in range(1, TRAIN_EPISODES + 1):
        state, _ = env.reset()

        # Begin with exploration and gradually reduce it.
        epsilon = max(0.05, 1.0 - episode / 40_000)

        action = choose_action(
            q_table, state, epsilon, action_rng
        )

        next_state, reward, terminated, truncated, info = (
            env.step(action)
        )

        # Terminal episodes have no future reward.
        future_value = (
            0.0 if terminated
            else float(np.max(q_table[next_state]))
        )

        target = reward + DISCOUNT_FACTOR * future_value

        q_table[state, action] += LEARNING_RATE * (
            target - q_table[state, action]
        )

        history.append({
            "episode": episode,
            "reward": reward,
            "click": info["click"],
            "epsilon": epsilon,
            "steps": 1,
        })

        if episode % 10_000 == 0:
            recent_rewards = [
                row["reward"] for row in history[-5_000:]
            ]

            print(
                f"Episode {episode:,} | "
                f"Epsilon: {epsilon:.2f} | "
                f"Recent mean reward: "
                f"${np.mean(recent_rewards):.4f}"
            )

    env.close()
    return q_table, history
# %%

# %% 6. COMPARE THE LEARNED POLICY WITH RANDOM PLACEMENT
def evaluate_agent(q_table):
    rng = np.random.default_rng(SEED + 100)

    states = rng.integers(
        len(PROFILES), size=TEST_IMPRESSIONS
    )
    click_draws = rng.random(TEST_IMPRESSIONS)

    random_actions = rng.integers(
        len(PLACEMENTS), size=TEST_IMPRESSIONS
    )

    # Select the highest-Q action for each visitor profile.
    learned_actions = np.argmax(q_table, axis=1)[states]

    results = []

    policies = [
        ("Random", random_actions),
        ("Q-learning", learned_actions),
    ]

    for name, actions in policies:
        probabilities = CLICK_PROBABILITIES[states, actions]
        clicks = click_draws < probabilities

        total_clicks = int(clicks.sum())
        revenue = total_clicks * CLICK_VALUE
        cost = float(COSTS[actions].sum())
        profit = revenue - cost

        ctr = total_clicks / TEST_IMPRESSIONS * 100
        roi = profit / cost * 100

        results.append({
            "policy": name,
            "impressions": TEST_IMPRESSIONS,
            "clicks": total_clicks,
            "ctr_percent": ctr,
            "revenue": revenue,
            "cost": cost,
            "profit": profit,
            "roi_percent": roi,
        })

    return results
# %%

# %% 7. SAVE RESULTS AND CREATE VISUALS
def save_csv(path, rows):
    with path.open("w", newline="") as file:
        writer = csv.DictWriter(
            file, fieldnames=rows[0].keys()
        )
        writer.writeheader()
        writer.writerows(rows)


def save_outputs(q_table, history, results):
    OUTPUT.mkdir(exist_ok=True)

    save_csv(OUTPUT / "training_history.csv", history)
    save_csv(OUTPUT / "evaluation_results.csv", results)

    np.save(OUTPUT / "q_table.npy", q_table)

    q_rows = []
    policy_rows = []

    for state, profile in enumerate(PROFILES):
        q_rows.append({
            "profile": profile,
            **{
                placement: float(q_table[state, action])
                for action, placement in enumerate(PLACEMENTS)
            },
        })

        best_action = int(np.argmax(q_table[state]))

        policy_rows.append({
            "profile": profile,
            "selected_placement": PLACEMENTS[best_action],
        })

    save_csv(OUTPUT / "q_table.csv", q_rows)
    save_csv(OUTPUT / "learned_policy.csv", policy_rows)

    # Chart 1: Average reward in blocks of 2,000 impressions.
    rewards = np.array([row["reward"] for row in history])
    block_size = 2_000

    block_means = rewards.reshape(-1, block_size).mean(axis=1)
    episode_numbers = np.arange(
        block_size, TRAIN_EPISODES + 1, block_size
    )

    fig, ax = plt.subplots(figsize=(8, 4.5))

    ax.plot(episode_numbers, block_means, color="black")
    ax.set_title("Q-learning training progress")
    ax.set_xlabel("Training episode: one impression each")
    ax.set_ylabel("Mean profit per impression ($)")
    ax.grid(alpha=0.2)

    fig.tight_layout()
    fig.savefig(
        OUTPUT / "training_progress.png", dpi=180
    )
    plt.close(fig)

    # Chart 2: Test CTR and simulated ROI.
    fig, axes = plt.subplots(1, 2, figsize=(9, 4.5))

    metrics = [
        ("ctr_percent", "CTR (%)"),
        ("roi_percent", "Simulated ROI (%)"),
    ]

    for ax, (metric, title) in zip(axes, metrics):
        labels = [row["policy"] for row in results]
        values = [row[metric] for row in results]

        bars = ax.bar(
            labels,
            values,
            color=["lightgray", "dimgray"],
            edgecolor="black",
        )

        ax.bar_label(bars, fmt="%.2f", padding=3)
        ax.set_title(title)
        ax.set_ylim(0, max(values) * 1.2)

    fig.suptitle(
        f"Held-out evaluation: "
        f"{TEST_IMPRESSIONS:,} impressions per policy"
    )

    fig.tight_layout()
    fig.savefig(
        OUTPUT / "policy_comparison.png", dpi=180
    )
    plt.close(fig)

    # Save a readable summary.
    summary = ["LEARNED POLICY"]

    for row in policy_rows:
        summary.append(
            f"{row['profile']}: "
            f"{row['selected_placement']}"
        )

    summary.append("\nHELD-OUT EVALUATION")

    for row in results:
        summary.append(
            f"{row['policy']}: "
            f"CTR={row['ctr_percent']:.2f}% | "
            f"ROI={row['roi_percent']:.2f}% | "
            f"Profit=${row['profit']:.2f}"
        )

    summary_text = "\n".join(summary)

    print("\n" + summary_text)
    (OUTPUT / "results_summary.txt").write_text(summary_text)

    print(f"\nResults saved to: {OUTPUT}")
# %%

# %% 8. RUN THE PROJECT
if __name__ == "__main__":
    trained_q_table, training_history = train_agent()

    evaluation_results = evaluate_agent(trained_q_table)

    save_outputs(
        trained_q_table,
        training_history,
        evaluation_results,
    )
